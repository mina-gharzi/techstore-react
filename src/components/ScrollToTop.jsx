import { useEffect } from "react";
import { useLocation } from "react-router-dom";

// ======================================================
// ScrollToTop
//
// React Router به‌طور پیش‌فرض موقعیت اسکرول رو بین صفحات حفظ
// می‌کنه (چون از نظر فنی SPA هیچ "لود صفحه"ی واقعی‌ای نداره).
// یعنی اگه توی صفحه‌ی محصولات پایین اسکرول کرده باشی و بعد
// روی یه محصول کلیک کنی، صفحه‌ی جزئیات هم از همون نقطه (نه
// از بالا) شروع می‌شه - که گیج‌کننده‌ست.
//
// این کامپوننت هیچ‌چیزی رندر نمی‌کنه؛ فقط هر بار مسیر (pathname)
// عوض بشه، پنجره رو به بالای صفحه می‌بره. باید داخل
// <BrowserRouter> قرار بگیره تا به useLocation دسترسی داشته باشه.
// ======================================================

export default function ScrollToTop() {
  const { pathname } = useLocation();

  useEffect(() => {
    window.scrollTo(0, 0);
  }, [pathname]);

  return null;
}
import { useEffect } from "react";
import { APP_NAME } from "../utils/constants";

// ======================================================
// usePageTitle
//
// قبلاً همه‌ی صفحات فقط عنوان ثابتی که توی index.html نوشته شده
// بود رو داشتن ("TechStore | فروشگاه آنلاین لوازم دیجیتال") -
// یعنی تب مرورگر برای صفحه‌ی محصولات، سبد خرید، و جزئیات یک
// محصول خاص، همه دقیقاً یک اسم داشتن. این هم برای کاربر گیج‌کننده
// بود (نمی‌شد از روی تب‌های باز فهمید کدوم صفحه‌ست) و هم برای
// SEO ضعیف بود (گوگل هیچ سرنخی از محتوای هر صفحه نداشت).
//
// این هوک عنوان تب مرورگر رو با document.title مستقیم عوض می‌کنه؛
// نیازی به نصب پکیج جدید (مثل react-helmet) نیست چون فقط یک
// خط ساده‌ست. با هر بار عوض شدن title، عنوان آپدیت می‌شه و وقتی
// کامپوننت unmount بشه هم به‌صورت خودکار توسط صفحه‌ی بعدی
// بازنویسی می‌شه (نیازی به پاک‌سازی دستی نیست).
//
// استفاده:
//   usePageTitle("محصولات");        -> "محصولات | TechStore"
//   usePageTitle();                 -> فقط "TechStore" (صفحه‌ی اصلی)
// ======================================================

export function usePageTitle(title) {
  useEffect(() => {
    document.title = title ? `${title} | ${APP_NAME}` : APP_NAME;
  }, [title]);
}